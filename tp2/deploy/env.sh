#!/usr/bin/env bash
set -euo pipefail

EXP_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
BASE=${BASE:-$(cd "$EXP_DIR/.." && pwd)}

RUN=${RUN:-mc-qwen38-tp2}
IMAGE=${IMAGE:-flashnext-base:090c06d563692003}
MODEL=${MODEL:-/home/admin/chy/data/models/qwen38-flash-next-serving-bf16mtp-v1}
MASTER_IP=${MASTER_IP:-10.240.23.1}
MASTER_PORT=${MASTER_PORT:-50051}
MASTER_ADDR=${MASTER_ADDR:-${MASTER_IP}:${MASTER_PORT}}
MASTER_METRICS_PORT=${MASTER_METRICS_PORT:-9003}
MASTER_ENABLE_OFFLOAD=${MASTER_ENABLE_OFFLOAD:-false}
STORE_PORT=${STORE_PORT:-50052}
STORE_SEGMENT_SIZE=${STORE_SEGMENT_SIZE:-16gb}
STORE_LOCAL_BUFFER_SIZE=${STORE_LOCAL_BUFFER_SIZE:-1gb}
STORE_CONTAINER_MEMORY_GIB=${STORE_CONTAINER_MEMORY_GIB:-24}
STANDALONE_STORAGE=${STANDALONE_STORAGE:-1}
MOONCAKE_GLOBAL_SEGMENT_SIZE=${MOONCAKE_GLOBAL_SEGMENT_SIZE:-32gb}

MOONCAKE_MODE=${MOONCAKE_MODE:-1}
MOONCAKE_PROTOCOL=${MOONCAKE_PROTOCOL:-rdma}
MOONCAKE_METADATA=${MOONCAKE_METADATA:-P2PHANDSHAKE}
MOONCAKE_DEVICE=${MOONCAKE_DEVICE:-}
MOONCAKE_DEVICE_RANK0=${MOONCAKE_DEVICE_RANK0:-}
MOONCAKE_DEVICE_RANK1=${MOONCAKE_DEVICE_RANK1:-}
MC_MS_FILTERS=${MC_MS_FILTERS:-rocep1s0f0,rocep1s0f1,roceP2p1s0f0,roceP2p1s0f1}

HICACHE_SIZE_GIB=${HICACHE_SIZE_GIB:-8}
HICACHE_HOST_MEMORY_MODE=${HICACHE_HOST_MEMORY_MODE:-cache}
SSD_OFFLOAD=${SSD_OFFLOAD:-0}
SSD_OFFLOAD_PATH=${SSD_OFFLOAD_PATH:-/cache/mooncake-ssd}
HICACHE_PREFETCH=${HICACHE_PREFETCH:-timeout}
HICACHE_WRITE_POLICY=${HICACHE_WRITE_POLICY:-write_back}
HICACHE_IO_BACKEND=${HICACHE_IO_BACKEND:-kernel}
HICACHE_MEM_LAYOUT=${HICACHE_MEM_LAYOUT:-page_first}
HICACHE_STORAGE_BACKEND=${HICACHE_STORAGE_BACKEND:-mooncake}
HICACHE_STORAGE_EXTRA_CONFIG=${HICACHE_STORAGE_EXTRA_CONFIG:-}
PAGE_SIZE=${PAGE_SIZE:-64}
CHUNKED_PREFILL_SIZE=${CHUNKED_PREFILL_SIZE:-4096}
MEMFRAC=${MEMFRAC:-0.55}
MEMLIMIT_GIB=${MEMLIMIT_GIB:-100}
MAXREQ=${MAXREQ:-4}
MAXTOKENS=${MAXTOKENS:-65536}
MAMBACACHE=${MAMBACACHE:-20}
MAMBA_RADIX_STRATEGY=${MAMBA_RADIX_STRATEGY:-extra_buffer}
MAMBA_SSM_DTYPE=${MAMBA_SSM_DTYPE:-}
MAMBA_MAX_STATES_PER_PATH=${MAMBA_MAX_STATES_PER_PATH:--1}
MAMBA_TRACK_INTERVAL=${MAMBA_TRACK_INTERVAL:-256}
DETERMINISTIC=${DETERMINISTIC:-0}
RANDOM_SEED=${RANDOM_SEED:-20261103}
CTX=${CTX:-16384}
PORT=${PORT:-31000}
CONFIG=${CONFIG:-A}
QUANT=${QUANT:-modelopt_fp4}
KV=${KV:-auto}
GROUP=${GROUP:-G23}
WORLD=${WORLD:-2}
MASTER=${MASTER:-10.240.23.1:29680}
IFACE=${IFACE:-enp1s0f0np0}
NCCL_IB_DISABLE=${NCCL_IB_DISABLE:-1}

EVICTION_HIGH_WATERMARK=${EVICTION_HIGH_WATERMARK:-0.85}
EVICTION_RATIO=${EVICTION_RATIO:-0.20}
KV_LEASE_TTL=${KV_LEASE_TTL:-10m}
KV_SOFT_PIN_TTL=${KV_SOFT_PIN_TTL:-30m}

NODE_HOST=$(hostname -s)
if [ -z "${LOCAL_IP:-}" ] || [ -z "${NODE_RANK:-}" ]; then
  case "$NODE_HOST" in
    spark-33a3)
      LOCAL_IP=${LOCAL_IP:-10.240.23.1}
      NODE_RANK=${NODE_RANK:-0}
      ;;
    spark-ef42)
      LOCAL_IP=${LOCAL_IP:-10.240.23.2}
      NODE_RANK=${NODE_RANK:-1}
      ;;
    *)
      echo "Unknown Spark host ${NODE_HOST}. Set LOCAL_IP and NODE_RANK explicitly." >&2
      exit 2
      ;;
  esac
fi

RANK=${RANK:-${NODE_RANK}}
if [ -z "$MOONCAKE_DEVICE" ]; then
  case "$RANK" in
    0) MOONCAKE_DEVICE=${MOONCAKE_DEVICE_RANK0:-} ;;
    1) MOONCAKE_DEVICE=${MOONCAKE_DEVICE_RANK1:-} ;;
  esac
fi
PEER_URL=${PEER_URL:-}
GUARDIAN_PORT=${GUARDIAN_PORT:-9101}
if [ -z "$PEER_URL" ]; then
  if [ "$RANK" = "0" ]; then
    PEER_URL=http://10.240.23.2:${GUARDIAN_PORT}/guardian
  else
    PEER_URL=http://10.240.23.1:${GUARDIAN_PORT}/guardian
  fi
fi

CONFIG_DIR=${CONFIG_DIR:-$EXP_DIR/config/$RUN}
LOG_DIR=${LOG_DIR:-$EXP_DIR/logs/$RUN}
CACHE=${CACHE:-$BASE/cache/$RUN/rank$RANK}
SGLANG_CONFIG=${SGLANG_CONFIG:-$CONFIG_DIR/mooncake_sglang.json}
STORE_CONFIG=${STORE_CONFIG:-$CONFIG_DIR/store-rank$RANK.json}
MASTER_CONTAINER=${MASTER_CONTAINER:-$RUN-mooncake-master}
STORE_CONTAINER=${STORE_CONTAINER:-$RUN-mooncake-store-r$RANK}
CONTAINER=${CONTAINER:-$RUN-r$RANK}

MOONCAKE_MASTER_BIN=${MOONCAKE_MASTER_BIN:-/opt/sglang/lib/python3.12/site-packages/mooncake/mooncake_master}
MOONCAKE_PYTHON=${MOONCAKE_PYTHON:-/opt/sglang/bin/python3}

export EXP_DIR BASE RUN IMAGE MODEL MASTER_IP MASTER_PORT MASTER_ADDR MASTER_METRICS_PORT MASTER_ENABLE_OFFLOAD
export STORE_PORT STORE_SEGMENT_SIZE STORE_LOCAL_BUFFER_SIZE STORE_CONTAINER_MEMORY_GIB
export STANDALONE_STORAGE MOONCAKE_GLOBAL_SEGMENT_SIZE
export MOONCAKE_MODE MOONCAKE_PROTOCOL MOONCAKE_METADATA MOONCAKE_DEVICE MC_MS_FILTERS
export MOONCAKE_DEVICE_RANK0 MOONCAKE_DEVICE_RANK1
export HICACHE_SIZE_GIB HICACHE_PREFETCH HICACHE_WRITE_POLICY PAGE_SIZE
export HICACHE_IO_BACKEND HICACHE_MEM_LAYOUT CHUNKED_PREFILL_SIZE
export HICACHE_STORAGE_BACKEND HICACHE_STORAGE_EXTRA_CONFIG
export HICACHE_HOST_MEMORY_MODE SSD_OFFLOAD SSD_OFFLOAD_PATH
export MEMFRAC MEMLIMIT_GIB MAXREQ MAXTOKENS MAMBACACHE CTX PORT CONFIG QUANT KV GROUP WORLD MASTER IFACE NCCL_IB_DISABLE
export MAMBA_RADIX_STRATEGY MAMBA_SSM_DTYPE MAMBA_MAX_STATES_PER_PATH MAMBA_TRACK_INTERVAL
export DETERMINISTIC RANDOM_SEED
export EVICTION_HIGH_WATERMARK EVICTION_RATIO KV_LEASE_TTL KV_SOFT_PIN_TTL
export NODE_HOST LOCAL_IP NODE_RANK RANK PEER_URL GUARDIAN_PORT CONFIG_DIR LOG_DIR CACHE SGLANG_CONFIG STORE_CONFIG
export MASTER_CONTAINER STORE_CONTAINER CONTAINER MOONCAKE_MASTER_BIN MOONCAKE_PYTHON

